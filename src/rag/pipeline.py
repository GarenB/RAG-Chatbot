
import os

import weaviate
from weaviate.classes.init import AdditionalConfig, Timeout
from weaviate.classes.config import Configure, Property, DataType

from langchain_weaviate import WeaviateVectorStore
from langchain_community.document_loaders import PyPDFLoader
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_community.vectorstores import FAISS
from langchain_ollama import OllamaEmbeddings, ChatOllama
from langchain_core.documents import Document
from langchain_core.prompts import ChatPromptTemplate
from langchain_classic.chains.combine_documents import create_stuff_documents_chain
from langchain_classic.chains import create_retrieval_chain
from langchain_classic.retrievers.contextual_compression import ContextualCompressionRetriever
from langchain_classic.retrievers.document_compressors import CrossEncoderReranker

from langchain_community.cross_encoders import HuggingFaceCrossEncoder


class RAGPipeline:
    def __init__(self):
        self.ollama_url = os.getenv("OLLAMA")
        self.embed_model = os.getenv("EMBED_MODEL")
        self.chat_model = os.getenv("CHAT_MODEL")
        self.cross_encoder_model = os.getenv("CROSS_ENCODER_MODEL")
        
        self.embeddings = OllamaEmbeddings(
            model=self.embed_model,
            base_url=self.ollama_url
        )
        
        self.llm = ChatOllama(
            model=self.chat_model,
            base_url=self.ollama_url,
            temperature=0
        )
        self.retriever = None
        self.rag_chain = None
        
        self.weaviate_client = weaviate.connect_to_local(
            host="localhost",
            port=8080,
            grpc_port=50051,
            additional_config=AdditionalConfig(
                    timeout=Timeout(init=30, query=60, insert=120)
                )
        )
        
        self.collection_name="DocumentChunks"
        self.cross_encoder = HuggingFaceCrossEncoder(model_name=self.cross_encoder_model)
        self.reranker = CrossEncoderReranker(model = self.cross_encoder, top_n=3)
        
    def create_collection(self):
        if not self.weaviate_client.collections.exists(self.collection_name):
            self.weaviate_client.collections.create(
                name=self.collection_name,
                vector_config=Configure.Vectors.self_provided(), # we provide the vectors, they are not generated by weaviate
                properties=[
                    Property(
                        name="content", # text of a chunk
                        data_type=DataType.TEXT
                    ),
                    Property(
                        name="source", # original pdf file name
                        data_type=DataType.TEXT
                    ),
                    Property(
                        name="page", # pdf page number
                        data_type=DataType.INT
                    )
                ]
            )
            
    def pdf_to_chunk(self, file_path: str, filename: str):
        loader = PyPDFLoader(file_path)
        documents = loader.load() # extract text
        
        splitter = RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=200)
        chunks = splitter.split_documents(documents) # split into chunks
        
        for chunk in chunks:
            chunk.metadata["source"] = filename # keeping track of file name
            
        return chunks
    
    def clean_metadata(self, chunks):
        cleaned = []
        for chunk in chunks:
            cleaned.append(
                Document(
                    page_content=chunk.page_content,
                    metadata={
                        "source": str(chunk.metadata.get("source", "unknown")),
                        "page": int(chunk.metadata.get("page", 0))
                    }
                )
            )
        return cleaned

    
    def upload_pdf(self, file_path: str, filename: str):
        chunks = self.pdf_to_chunk(file_path, filename)
        
        if not chunks:
            return 0
        
        chunks = self.clean_metadata(chunks)
        self.vectorstore.add_documents(chunks)
        
        return len(chunks)
    
    def store_chunks(self, chunks):
        if not chunks:
            return 0

        self.vectorstore.add_documents(chunks)

        return len(chunks)
    
    def initialize_vectorstore(self):
        self.vectorstore = WeaviateVectorStore(
            client=self.weaviate_client,
            index_name=self.collection_name,
            text_key="content",
            embedding=self.embeddings,
            attributes=["source", "page"]
        )

    def build_retriever(self):
        self.retriever = self.vectorstore.as_retriever(
            search_kwargs={"k": 5}
        )
        
        self.compression_retriever = ContextualCompressionRetriever(
            base_compressor=self.reranker,
            base_retriever=self.retriever
        )
        
        return self.compression_retriever

    def build_chain(self):
        system_prompt = """
You are a question-answering assistant that must answer exclusively
using the information provided in the context.

STRICT RULES:
1. Use ONLY information explicitly available in the context.
2. Do not use your pretrained knowledge or outside information.
3. Do not make assumptions or fill in missing information.
4. If the context does not contain enough information to answer
   the question, respond exactly:
   "I don't know based on the provided documents."
5. Even if you already know the answer, you MUST follow these rules.

Context:
{context}
"""

        prompt = ChatPromptTemplate.from_messages([
            ("system", system_prompt),
            ("human", "{input}")
        ])

        question_answer_chain = create_stuff_documents_chain(
            self.llm,
            prompt
        )

        self.rag_chain = create_retrieval_chain(
            self.compression_retriever,
            question_answer_chain
        )

    def initialize(self):
        self.create_collection()
        self.initialize_vectorstore()
        self.build_retriever()
        self.build_chain()

    def ask(self, question: str):
        if self.rag_chain is None:
            raise RuntimeError("RAG pipeline is not initialized.")

        response = self.rag_chain.invoke({
            "input": question
        })

        sources = []

        for doc in response["context"]:
            sources.append({
                "source": doc.metadata.get("source", "Unknown"),
                "content": doc.page_content
            })

        return {
            "question": question,
            "answer": response["answer"],
            "sources": sources
        }

    async def ask_stream(self, question: str):
        if self.rag_chain is None:
            raise RuntimeError("RAG pipeline is not initialized.")

        async for chunk in self.rag_chain.astream({
            "input": question
        }):

            # Retrieved documents
            context = chunk.get("context")

            if context:
                sources = [
                    {
                        "source": doc.metadata.get("source", "Unknown"),
                        "content": doc.page_content
                    }
                    for doc in context
                ]

                yield {
                    "event": "sources",
                    "data": sources
                }

            # Generated answer
            answer_chunk = chunk.get("answer")

            if answer_chunk:
                yield {
                    "event": "token",
                    "data": answer_chunk
                }

        yield {
            "event": "done",
            "data": "[DONE]"
        }


